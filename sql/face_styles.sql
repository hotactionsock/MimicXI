-- face_styles: lookup table for the web character creator.
-- Maps each face byte value to display metadata and (eventually) preview image paths.
-- The game server never reads this table — it is web-UI only.
--
-- face_id values:
--   0-15  : original faces (A/B variants, paired per face number)
--   16-23 : custom C-variant faces requiring matching client DAT files
--
-- Populate preview_path once you have extracted face preview images from the DATs.

CREATE TABLE IF NOT EXISTS `face_styles` (
  `face_id`      TINYINT UNSIGNED NOT NULL,
  `race_id`      TINYINT UNSIGNED NOT NULL,
  `face_num`     TINYINT UNSIGNED NOT NULL COMMENT '1-8',
  `variant`      CHAR(1)          NOT NULL COMMENT 'A, B, or C',
  `preview_path` VARCHAR(255)     NOT NULL DEFAULT '' COMMENT 'web-relative path to preview image',
  `is_custom`    TINYINT(1)       NOT NULL DEFAULT 0  COMMENT '1 for C-variant faces',
  PRIMARY KEY (`face_id`, `race_id`),
  KEY `idx_race` (`race_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

