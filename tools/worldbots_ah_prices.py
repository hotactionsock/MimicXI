#!/usr/bin/env python3
"""Turn a price sheet into SQL for world_bot_ah_prices (manual Auction House
prices for world bots - see src/map/utils/botauction.h).

Accepts either:
  * an ffxiahbot items CSV (itemid, name, sell_single, buy_single,
    price_single, stock_single, sell_stacks, buy_stacks, price_stacks,
    stock_stacks) - e.g. one you scraped with `ffxiahbot scrub` yourself.
    NOTE: the items.csv / items75.csv bundled with ffxiahbot are NOT market
    prices - price_single is just the vendor price (item_basic.BaseSell) and
    price_stacks 12x that - so importing them gains nothing.
  * a simple sheet: itemid, price_single, price_stacks[, allow]
    (0 = no override for that kind; allow 0 = bots never list the item)

Rows where both prices are 0 and allow is 1 are skipped. Prints SQL to stdout:

    python3 tools/worldbots_ah_prices.py prices.csv > ah_prices.sql
    mysql -u <user> -p <db> < ah_prices.sql

Re-importing updates existing rows. Prices set in game with
`!worldbot ahprice` live in the same table.
"""

import argparse
import csv
import sys
import time


def to_int(value, default=0):
    try:
        return int(float(str(value).strip()))
    except (TypeError, ValueError):
        return default


def rows_from(path):
    with open(path, newline="", encoding="utf-8") as handle:
        reader = csv.reader(handle, skipinitialspace=True)
        header = [h.strip().lower() for h in next(reader)]

        def col(row, name):
            return row[header.index(name)] if name in header and header.index(name) < len(row) else None

        ffxiahbot = "price_single" in header and "sell_single" in header
        for raw in reader:
            row = [c.strip() for c in raw]
            if not row or not row[0] or row[0].startswith("#"):
                continue

            itemid = to_int(row[0], -1)
            if itemid <= 0 or itemid > 65535:
                continue

            if ffxiahbot:
                sell_single = to_int(col(row, "sell_single")) == 1
                sell_stacks = to_int(col(row, "sell_stacks")) == 1
                single = to_int(col(row, "price_single")) if sell_single else 0
                stacks = to_int(col(row, "price_stacks")) if sell_stacks else 0
                allow = 1 if (sell_single or sell_stacks) else 0
            else:
                single = to_int(row[1] if len(row) > 1 else 0)
                stacks = to_int(row[2] if len(row) > 2 else 0)
                allow = to_int(row[3], 1) if len(row) > 3 else 1

            # ffxiahbot uses 1 as "no price"
            single = 0 if single <= 1 else single
            stacks = 0 if stacks <= 1 else stacks

            if single == 0 and stacks == 0 and allow == 1:
                continue

            yield itemid, single, stacks, 1 if allow else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("csv", help="price sheet (ffxiahbot items CSV, or itemid,price_single,price_stacks[,allow])")
    args = parser.parse_args()

    now = int(time.time())
    count = 0
    print("-- world_bot_ah_prices, generated by tools/worldbots_ah_prices.py from {}".format(args.csv))
    for itemid, single, stacks, allow in rows_from(args.csv):
        print(
            "INSERT INTO world_bot_ah_prices (itemid, price_single, price_stacks, allow, updated) "
            "VALUES ({}, {}, {}, {}, {}) ON DUPLICATE KEY UPDATE price_single = VALUES(price_single), "
            "price_stacks = VALUES(price_stacks), allow = VALUES(allow), updated = VALUES(updated);".format(itemid, single, stacks, allow, now)
        )
        count += 1

    print("-- {} item(s)".format(count), file=sys.stderr)


if __name__ == "__main__":
    main()
